export const dictionaries = { it, en } satisfies Record<'it' | 'en', Record<MessageKey, string>>

export type Locale = keyof typeof dictionaries

export function resolveLocale(setting: Language, systemLanguage: string): Locale {
  if (setting !== 'auto') return setting
  return systemLanguage.toLowerCase().startsWith('it') ? 'it' : 'en'
}

export type Translate = (key: MessageKey, params?: Record<string, string | number>) => string

export function makeTranslate(locale: Locale): Translate {
  const dict = dictionaries[locale]
  return (key, params) => {
    let text: string = dict[key] ?? it[key] ?? key
    if (params) for (const [k, v] of Object.entries(params)) text = text.replaceAll(`{${k}}`, String(v))
    return text
  }
}

export const I18nContext = createContext<{ t: Translate; locale: Locale }>({ t: makeTranslate('it'), locale: 'it' })

export const useI18n = (): { t: Translate; locale: Locale } => useContext(I18nContext)
